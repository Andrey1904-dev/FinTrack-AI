-- Telegram linking, notification preferences and service-role-only bot state.

create table if not exists public.telegram_link_codes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  code text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists telegram_link_codes_expiry_idx on public.telegram_link_codes(expires_at);

create table if not exists public.telegram_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  telegram_chat_id text not null unique,
  username text,
  first_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.telegram_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  notifications_enabled boolean not null default true,
  credit_reminders boolean not null default true,
  recurring_reminders boolean not null default true,
  budget_alerts boolean not null default true,
  weekly_digest boolean not null default true,
  reminder_days integer[] not null default array[3,1,0],
  timezone text not null default 'UTC',
  updated_at timestamptz not null default now(),
  constraint telegram_reminder_days_valid check (
    cardinality(reminder_days) between 1 and 5 and reminder_days <@ array[0,1,2,3,5,7]
  )
);

create table if not exists public.telegram_pending_operations (
  token text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  telegram_chat_id text not null,
  draft jsonb not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists telegram_pending_operations_expiry_idx
  on public.telegram_pending_operations(expires_at);

create table if not exists public.telegram_operations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  telegram_chat_id text not null,
  operation_client_id text not null,
  amount numeric(14,2) not null,
  category text not null,
  note text not null default '',
  operation_date date not null,
  created_at timestamptz not null default now(),
  unique (user_id, operation_client_id)
);
create index if not exists telegram_operations_latest_idx
  on public.telegram_operations(user_id, created_at desc);

create table if not exists public.telegram_webhook_updates (
  update_id bigint primary key,
  created_at timestamptz not null default now()
);
create table if not exists public.telegram_rate_limits (
  telegram_chat_id text primary key,
  window_started_at timestamptz not null default now(),
  message_count integer not null default 0
);
create table if not exists public.telegram_notification_claims (
  user_id uuid not null references auth.users(id) on delete cascade,
  event_key text not null,
  state text not null default 'processing' check (state in ('processing','sent')),
  locked_until timestamptz not null default (now() + interval '5 minutes'),
  sent_at timestamptz,
  primary key (user_id, event_key)
);

